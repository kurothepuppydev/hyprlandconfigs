#!/usr/bin/env python3
"""Regenerate application color files from the KURO palette."""
import argparse
import json
from pathlib import Path


def render(root, colors):
    hypr = [
        f"${name.replace('-', '_')} = rgba({value[1:]}ff)"
        if len(value) == 7
        else f"${name.replace('-', '_')} = rgba({value[1:]})"
        for name, value in colors.items()
    ]
    hypr.append(f"$shadow = rgba({colors['surface-dark'][1:]}80)")

    terminal = {
        "background": "surface-dark",
        "foreground": "ivory",
        "cursor": "lavender",
        "cursor_text_color": "surface-dark",
        "selection_background": "deep-violet",
        "selection_foreground": "ivory",
    }
    ansi = [
        "obsidian", "error", "success", "warning", "info", "lavender", "cyan", "ash",
        "border", "error", "success", "warning", "info", "lavender-light", "cyan", "ivory",
    ]
    terminal.update({f"color{index}": name for index, name in enumerate(ansi)})

    dunst = [
        '[global]',
        '    width = 320',
        '    offset = (12, 12)',
        '    origin = top-right',
        '    font = Inter 10',
        '    padding = 12',
        '    horizontal_padding = 12',
        '    frame_width = 1',
        '    corner_radius = 6',
        '    markup = full',
        '    format = "<b>%s</b>\\n%b"',
        '    mouse_left_click = close_current',
        '    mouse_right_click = do_action',
    ]
    for urgency, frame, timeout in [
        ("low", "border", 4), ("normal", "lavender", 6), ("critical", "error", 0)
    ]:
        dunst.extend([
            "",
            f"[urgency_{urgency}]",
            f'    background = "{colors["surface"]}"',
            f'    foreground = "{colors["ivory"]}"',
            f'    frame_color = "{colors[frame]}"',
            f"    timeout = {timeout}",
        ])

    return {
        root / "hypr/colors.conf": ["# Generated by render-palette.py", *hypr],
        root / "waybar/colors.css": [
            "/* Generated by render-palette.py */",
            *[
                f"@define-color {name.replace('-', '_')} {value};"
                for name, value in colors.items() if len(value) == 7
            ],
        ],
        root / "rofi/colors.rasi": [
            "/* Generated by render-palette.py */",
            "* {",
            *[f"    {name}: {value};" for name, value in colors.items()],
            "}",
        ],
        root / "kitty/colors.conf": [
            "# Generated by render-palette.py",
            *[f"{option} {colors[name]}" for option, name in terminal.items()],
        ],
        root / "dunst/dunstrc": ["# Generated by render-palette.py", *dunst],
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check generated files")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    colors = json.loads((root / "kuro/palette.json").read_text())
    stale = []
    for path, lines in render(root, colors).items():
        content = "\n".join(lines) + "\n"
        if args.check:
            if not path.is_file() or path.read_text() != content:
                stale.append(str(path.relative_to(root)))
        else:
            path.write_text(content)
    if stale:
        parser.exit(1, "Regenerate: " + ", ".join(stale) + "\n")


if __name__ == "__main__":
    main()
